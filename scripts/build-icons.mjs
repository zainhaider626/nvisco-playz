// Bundles the Lucide icons the UI uses into public/js/icons.js (ISC licence) and copies the Inter font.
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
const require = createRequire(import.meta.url);
const dir = path.dirname(require.resolve('lucide-static/package.json')) + '/icons';
const NAMES = ['store', 'factory', 'building-2', 'house', 'car', 'sailboat', 'plane', 'watch', 'smartphone', 'frame', 'trophy', 'star', 'wallet', 'lock', 'check', 'chevron-right', 'chevron-left',
  'chevron-down', 'users', 'search', 'zap', 'coins', 'trending-up', 'trending-down', 'settings', 'share-2', 'copy', 'external-link', 'info', 'x', 'shield', 'globe', 'layout-grid', 'chart-candlestick',
  'crown', 'mail', 'log-out', 'user', 'briefcase', 'badge-check', 'map-pin', 'flag', 'bell', 'pointer', 'hand-coins', 'banknote', 'gem', 'rocket', 'sparkles', 'arrow-up', 'arrow-up-right', 'chevrons-up',
  'chevrons-down', 'medal', 'layers', 'wifi', 'nfc', 'cpu', 'link', 'eye', 'rotate-ccw', 'clock', 'target', 'circle-dollar-sign', 'building', 'chart-line', 'trophy', 'megaphone', 'handshake', 'shield-check'];
const out = {}; const missing = [];
for (const n of NAMES) {
  const f = `${dir}/${n}.svg`;
  if (!fs.existsSync(f)) { missing.push(n); continue; }
  const s = fs.readFileSync(f, 'utf8');
  out[n] = s.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/\s+/g, ' ').trim();
}
fs.writeFileSync('public/js/icons.js', `// generated by scripts/build-icons.mjs (Lucide, ISC licence)
const P = ${JSON.stringify(out)};
export const ic = (name, size = 20, cls = '', sw = 1.9) => \`<svg class="ic \${cls}" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="\${sw}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${P[name] || ''}</svg>\`;
export const hasIcon = (n) => n in P;
`);
fs.mkdirSync('public/fonts', { recursive: true });
const fdir = path.dirname(require.resolve('@fontsource-variable/inter/package.json')) + '/files';
for (const f of ['inter-latin-wght-normal.woff2', 'inter-latin-ext-wght-normal.woff2']) fs.copyFileSync(`${fdir}/${f}`, `public/fonts/${f}`);
console.log('icons:', Object.keys(out).length, 'missing:', missing.join(', ') || 'none');
